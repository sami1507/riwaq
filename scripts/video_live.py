"""Real local HTTP video QA. No model/API generation and no external requests.

Synthetic visual fixtures are original controlled examples. An OPTIONAL existing
Arabic voice sample stays local and is excluded from distributable examples;
its rights and transcription are NOT certified by this test.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import sys
import time
import uuid
import httpx
from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parents[1]

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--arabic-audio',type=Path);a=parser.parse_args()
    folder=ROOT/'reports/video-live';folder.mkdir(exist_ok=True)
    report={'date':'2026-11-15','network_scope':'Loopback HTTP only; all operations are composition, not generated scenes','provider_cost':0,'downloads':0,'cases':[],'human_audio_listening_performed':False}
    c=httpx.Client(base_url='http://127.0.0.1:8765',headers={'X-Riwaq-Client':'local'},trust_env=False,timeout=60)
    def get(r):r.raise_for_status();return r.json()
    pid=get(c.post('/api/projects',json={'name':'[QA فيديو] نصوص ولغات وصوت مستورد'}))['id'];base=f'/api/projects/{pid}/video';report['project_id']=pid
    image=Image.new('RGBA',(640,360),(0,0,0,0));draw=ImageDraw.Draw(image);draw.rounded_rectangle((40,30,600,330),30,fill='#126456');draw.ellipse((255,125,385,255),fill='#D2A46E')
    raw=io.BytesIO();image.save(raw,'PNG');asset=get(c.post(base+'/assets',files={'file':('controlled-transparent.png',raw.getvalue())},data={'license':'Original procedural Riwaq QA fixture; CC0-1.0'}))
    def layer(id,text,y,start,end,language='ar',kind='title',width=640):
        return {'id':id,'kind':kind,'text':text,'start':start,'end':end,'x':20.0,'y':float(y),'width':float(width-40),'height':80.0,'language':language,'direction':'rtl' if language in ('ar','he') else 'ltr','font':'hebrew' if language=='he' else 'latin' if language in ('en','es') else 'arabic','size':25.0,'weight':600,'color':'#ffffff','align':'center'}
    def export(t,name):
        started=time.monotonic();body={'timeline_id':t['id'],'version':t['version'],'idempotency_key':uuid.uuid4().hex}
        j=get(c.post(base+'/jobs',json=body));again=get(c.post(base+'/jobs',json=body));assert again['id']==j['id']
        deadline=time.monotonic()+320
        while time.monotonic()<deadline:
            j=get(c.get(base+'/jobs/'+j['id']))
            if j['status'] not in ('queued','running','cancelling'):break
            time.sleep(.1)
        assert j['status']=='completed',j
        movie=c.get(base+'/jobs/'+j['id']+'/content');movie.raise_for_status();(folder/(name+'.mp4')).write_bytes(movie.content)
        poster=c.get(base+'/jobs/'+j['id']+'/poster');poster.raise_for_status();(folder/(name+'.png')).write_bytes(poster.content)
        assert hashlib.sha256(movie.content).hexdigest()==j['report']['output_sha256']
        return {'name':name,'timeline_id':t['id'],'version':t['version'],'job_id':j['id'],'wall_seconds':time.monotonic()-started,'report':j['report']}
    spec={'width':640,'height':360,'fps':24,'background':'#172B2A','clips':[{'id':'c1','asset_id':asset['id'],'duration':2.0,'motion':'pan_zoom'}],
          'texts':[layer('t1','رواق — مساحة للأفكار',18,0,2),layer('t2','اللّغة العربيّة',105,0,2),layer('s1','خصم 25% — السعر 199 ₪',260,0,2,kind='subtitle')]}
    t=get(c.post(base+'/timelines',json={'title':'نص عربي حرفي — أفقـي','spec':spec}));report['cases'].append(export(t,'arabic-landscape'))
    spec={'width':360,'height':640,'fps':30,'background':'#182B28','clips':[{'id':'c1','asset_id':asset['id'],'duration':3.0}],
          'texts':[layer('t1','Riwaq AI | إصدار 2.1',30,0,3,width=360),layer('t2','¡Información útil!\nEdición número 2',140,0,3,'es',width=360),layer('s1','שלום 42 ₪',490,.5,2.5,'he','subtitle',360)]}
    t=get(c.post(base+'/timelines',json={'title':'نص مختلط — عمودي','spec':spec}));report['cases'].append(export(t,'mixed-portrait'))
    if a.arabic_audio:
        raw=a.arabic_audio.read_bytes();sound=get(c.post(base+'/assets',files={'file':('existing-arabic-test.mp3',raw)},data={'license':'Existing local synthetic Piper QA sample. Rights chain unverified; do not redistribute. Not generated by this task.'}))
        length=sound['duration'];assert 0<length<20
        spec={'width':640,'height':360,'fps':24,'background':'#172B2A','clips':[{'id':'c1','asset_id':asset['id'],'duration':10.0,'motion':'pan_zoom'},{'id':'c2','asset_id':asset['id'],'duration':10.0}],
              'texts':[layer('t1','تعليق عربي مستورد',18,0,20),layer('s1','عينة صوت موجودة — توقيت يدوي',265,.5,4,kind='subtitle')],
              'audio':[{'id':'a1','asset_id':sound['id'],'start':0.0,'source_start':0.0,'duration':length,'gain':.6,'role':'narration'}]}
        t=get(c.post(base+'/timelines',json={'title':'اختبار صوت عربي موجود — لا يوزّع','spec':spec}));before=export(t,'arabic-audio-before');report['cases'].append(before)
        spec['texts'][1]['text']='مقطع صوت موجود — توقيت يدوي';spec['texts'][1]['start']=1.25;spec['texts'][1]['end']=5.25
        t=get(c.patch(base+'/timelines/'+t['id'],json={'title':t['title'],'expected_version':t['version'],'spec':spec}));after=export(t,'arabic-audio-after');report['cases'].append(after)
        assert before['report']['inputs']==after['report']['inputs']
        assert before['report']['audio']['tracks'][0]['requested_samples']==round(length*48000)
        report['arabic_voice_limit']='Imported existing test sample, no speech synthesis or gold transcript. Subtitle is a literal test label with manual timing, not an asserted translation/alignment. No human listening evaluation.'
        report['nonredistributable_outputs']=['arabic-audio-before.mp4','arabic-audio-after.mp4']
    report['source_first_attempt_success']={'initial_designs':3 if a.arabic_audio else 2,'initial_complete_exports_passed_technical_checks':3 if a.arabic_audio else 2,'intentional_edit_exports':1 if a.arabic_audio else 0,'intentional_edit_exports_passed_technical_checks':1 if a.arabic_audio else 0,'corrective_retries':0,'raw_model_generation_trials':0,'raw_generation_success_rate':None,'scope':'Controlled engineering examples only; technical decode/source checks are not overall visual quality or an estimate of first-try model success.'}
    (ROOT/'reports/video-live.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),'utf-8')
    print(json.dumps({'cases':len(report['cases']),'report':'reports/video-live.json','project_id':pid},ensure_ascii=False))

if __name__=='__main__':main()
