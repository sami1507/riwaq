import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const out=new URL('../../reports/',import.meta.url);
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];const outgoing=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if(!request.url().startsWith('http://127.0.0.1:8765')&&!request.url().startsWith('data:')&&!request.url().startsWith('blob:'))outgoing.push(request.url());});
await page.goto('http://127.0.0.1:8765');
await page.getByPlaceholder('ما الذي تريد العمل عليه؟').waitFor();
await page.locator('.app[aria-busy="false"]').waitFor();
await page.screenshot({path:new URL('web-ar-desktop.png',out).pathname.replace(/^\/(.:)/,'$1'),fullPage:true,animations:'disabled'});
assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
await page.getByRole('button',{name:'الإعدادات',exact:true}).click();
await page.getByRole('dialog').getByRole('combobox').last().selectOption('en');
await page.getByRole('button',{name:'Close / إغلاق'}).click();
await page.getByPlaceholder('What would you like to work on?').fill('Reply with exactly the number 42.');
await page.getByRole('button',{name:'Send',exact:true}).click();
await page.locator('.message.assistant').waitFor({timeout:30000});
await page.getByRole('button',{name:'Stop',exact:true}).waitFor({state:'hidden',timeout:190000});
const response=await page.locator('.message.assistant .markdown').last().innerText();
assert.ok(response.includes('42'),response);
await page.reload();
await page.locator('.app[aria-busy="false"]').waitFor();
await page.locator('.message.assistant .markdown').last().waitFor();
assert.equal(await page.locator('.message.assistant .markdown').last().innerText(),response);
await page.screenshot({path:new URL('web-en-chat.png',out).pathname.replace(/^\/(.:)/,'$1'),fullPage:true});
await page.getByRole('button',{name:'Dark',exact:true}).click();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.screenshot({path:new URL('web-dark.png',out).pathname.replace(/^\/(.:)/,'$1'),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1);
await page.screenshot({path:new URL('web-mobile.png',out).pathname.replace(/^\/(.:)/,'$1'),fullPage:true,animations:'disabled'});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
assert.equal(overflow,false,'Mobile horizontal overflow');
assert.deepEqual(errors,[]);assert.deepEqual(outgoing,[]);
await writeFile(new URL('browser-smoke.json',out),JSON.stringify({passed:true,real_model:true,response,restored:true,arabic_rtl:true,english_ltr:true,dark:true,mobile_overflow:overflow,page_errors:errors,external_requests:outgoing},null,2));
console.log('BROWSER LIVE SMOKE PASSED');
await browser.close();
